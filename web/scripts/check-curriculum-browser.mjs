import { loadSource } from "./load-source.mjs";
// Real UI + FastAPI workflows with isolated identity/storage and deterministic local AI.
// Run api/scripts/course_browser_fixture.py and the dev server described in docs/COURSE_STRUCTURE.md.
import assert from "node:assert/strict";
import { mkdirSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { S } = loadSource(new URL("../src/lib/strings.ts", import.meta.url));
const tracks = JSON.parse(readFileSync("../content/tracks.json", "utf8"));
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ headless: true, ...(process.env.COURSE_CHROME_PATH ? { executablePath: process.env.COURSE_CHROME_PATH } : {}) });
const base = process.env.COURSE_TEST_URL || "http://127.0.0.1:3107";
assert.equal(new URL(base).hostname, "127.0.0.1", "Use the isolated localhost fixture only");
const api = "http://127.0.0.1:8797";
const output = process.env.COURSE_SCREENSHOTS || "/tmp/yaqin-curriculum-ui";
mkdirSync(output, { recursive: true });
const uid = "00000000-0000-0000-0000-000000000001";
const user = { id: uid, email: "admin@example.test", role: "authenticated", aud: "authenticated", created_at: "2026-10-01T00:00:00Z", user_metadata: { name: "Test Admin" }, app_metadata: {} };
const expires = Math.floor(Date.now() / 1000) + 3600;
const token = [Buffer.from(JSON.stringify({ alg: "HS256", typ: "JWT" })).toString("base64url"), Buffer.from(JSON.stringify({ sub: uid, exp: expires, aud: "authenticated", role: "authenticated" })).toString("base64url"), "offline-signature"].join(".");
const session = { access_token: token, refresh_token: "offline-refresh", expires_at: expires, expires_in: 3600, token_type: "bearer", user };
const only = process.env.COURSE_CASE;
try {
  for (const lang of ["en", "ar"]) for (const mobile of [false, true]) {
    const label = `${mobile ? "mobile" : "desktop"}-${lang}`;
    if (only && only !== label) continue;
    const t = (bi) => bi[lang];
    const trackTitle = (id) => t(tracks.find((track) => track.id === id).title);
    const context = await browser.newContext({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1050 } });
    let profile = { role: "admin", preferred_track: "first-steps", daily_minutes: 10, onboarded: true, known_lessons: [], lang, display_name: "Test Admin" };
    const saved = new Map();
    const errors = [];
    await context.addInitScript(({ session, lang }) => {
      if (!localStorage.getItem("sb-127-auth-token")) localStorage.setItem("sb-127-auth-token", JSON.stringify(session));
      localStorage.setItem("yaqin.lang", lang);
    }, { session, lang });
    await context.route("http://127.0.0.1:8798/**", async (route) => {
      const request = route.request();
      const path = new URL(request.url()).pathname;
      const body = request.postData() ? request.postDataJSON() : {};
      let data = [];
      if (path.includes("profiles")) {
        if (request.method() === "PATCH") profile = { ...profile, ...body };
        data = profile;
      } else if (path.endsWith("/user")) data = user;
      else if (path.endsWith("/save_learning_progress")) {
        saved.set(body.p_lesson, { user_id: uid, lesson_id: body.p_lesson, card: body.p_card, cards_done: body.p_cards_done, explained: body.p_explained, quiz_score: body.p_quiz_score, completed_at: body.p_completed_at, note: body.p_note });
        data = null;
      } else if (path.endsWith("/progress")) data = [...saved.values()];
      await route.fulfill({ json: data, headers: { "Access-Control-Allow-Origin": "*", "Access-Control-Allow-Headers": "*", "Access-Control-Allow-Methods": "GET,POST,PATCH,OPTIONS" } });
    });
    const page = await context.newPage();
    page.setDefaultTimeout(30000);
    page.on("pageerror", (error) => errors.push(error.message));
    const screenshot = async (name) => {
      await page.evaluate(() => window.scrollTo(0, 0));
      await page.screenshot({ path: `${output}/${label}-${name}.png`, fullPage: true, animations: "disabled" });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    };
    const button = (text) => page.getByRole("button", { name: text, exact: true });
    const select = async (label, option) => {
      const field = page.getByRole("combobox", { name: new RegExp(`^${label}`) });
      if (await field.evaluate((node) => node.tagName === "SELECT")) { await field.selectOption({ label: option }); return; }
      await field.click();
      await page.getByRole("option", { name: option, exact: true }).click();
    };
    const C = S.curriculum;
    const config = async () => (await page.request.get(`${api}/api/curriculum`)).json();
    const waitSave = async (operation, path) => {
      const response = page.waitForResponse((r) => r.url() === `${api}/api/curriculum/${path}` && r.request().method() === "POST");
      await operation();
      assert.equal((await response).status(), 200);
      await page.waitForFunction(() => !document.querySelector('[aria-busy="true"]'));
      const toast = page.locator(".studio-toast:popover-open");
      await toast.getByText(t(C.saved), { exact: true }).waitFor();
      assert.equal(await toast.getAttribute("role"), "status");
      const position = await toast.evaluate((node) => ({ top: node.getBoundingClientRect().top, position: getComputedStyle(node).position }));
      assert.equal(position.position, "fixed");
      assert(position.top >= 0 && position.top <= 24, "Success stays at the top even when the page is scrolled");
    };
    const editTitle = async (en, ar) => {
      const dialog = page.getByRole("dialog");
      await dialog.getByLabel(t(C.english), { exact: true }).fill(en);
      await dialog.getByLabel(t(C.arabic), { exact: true }).fill(ar);
    };
    const saveDialog = async (path) => {
      await waitSave(() => page.getByRole("dialog").getByRole("button", { name: t(C.save), exact: true }).click(), path);
      await page.getByRole("dialog").waitFor({ state: "hidden" });
    };
    const removeDialog = async (path) => {
      await waitSave(() => page.getByRole("dialog").getByRole("button", { name: t(C.remove), exact: true }).click(), path);
      await page.getByRole("dialog").waitFor({ state: "hidden" });
    };
    const goTab = async (tab) => {
      await button(t(C[tab])).click();
      await page.waitForURL((url) => url.searchParams.get("tab") === tab);
      await page.getByRole("heading", { name: t(tab === "modules" ? C.modules : C[tab]), exact: true }).waitFor();
      assert.equal(await button(t(tab === "subjects" ? C.addLevel : C.addSubject)).count(), 0, "Only the active tab's management controls are rendered");
    };
    const name = `Curriculum check ${label}`;
    const arName = `مادة التحقق ${label}`;
    await page.goto(`${base}/studio/curriculum/?tab=subjects`);
    await page.getByRole("heading", { name: t(C.subjects), exact: true }).waitFor();
    await page.locator("tbody tr").first().waitFor();
    assert(await page.locator("tbody tr").filter({ hasText: lang === "ar" ? "الفقه" : "Fiqh" }).getByRole("button", { name: t(C.delete), exact: true }).isDisabled());
    await screenshot("subjects");
    await button(t(C.addSubject)).click();
    await editTitle(name, arName);
    await saveDialog("subjects");
    const subject = (await config()).subjects.find((s) => s.title.en === name);
    assert(subject);
    assert.deepEqual(subject.levels, [1, 2, 3, 4]);
    await page.locator("tbody tr").filter({ hasText: name }).getByRole("button", { name: t(C.edit), exact: true }).click();
    await editTitle(`${name} renamed`, `${arName} معدّل`);
    await saveDialog("subjects");
    assert.equal((await config()).subjects.find((s) => s.id === subject.id).title.en, `${name} renamed`);
    await goTab("levels");
    assert.equal(new URL(page.url()).searchParams.get("tab"), "levels");
    await button(t(C.addLevel)).click();
    await editTitle(`Extra level ${label}`, `مستوى إضافي ${label}`);
    await saveDialog("levels");
    const extra = (await config()).levels.find((l) => l.title.en === `Extra level ${label}`);
    assert.equal(extra.id, 5);
    await screenshot("levels");
    await goTab("subjects");
    await page.locator("tbody tr").filter({ hasText: `${name} renamed` }).getByRole("button", { name: t(C.edit), exact: true }).click();
    await page.getByRole("dialog").getByRole("checkbox", { name: lang === "en" ? extra.title.en : extra.title.ar, exact: true }).check();
    await saveDialog("subjects");
    await goTab("levels");
    await page.locator("tbody tr").filter({ hasText: `Extra level ${label}` }).getByRole("button", { name: t(C.delete), exact: true }).click();
    await screenshot("confirm");
    await page.getByRole("dialog").getByRole("button", { name: t(C.cancel), exact: true }).click();
    assert((await config()).levels.some((l) => l.id === 5));
    await page.locator("tbody tr").filter({ hasText: `Extra level ${label}` }).getByRole("button", { name: t(C.delete), exact: true }).click();
    await removeDialog("levels");
    assert.deepEqual((await config()).subjects.find((s) => s.id === subject.id).levels, [1, 2, 3, 4]);
    await goTab("modules");
    await page.getByRole("heading", { name: t(C.sections), exact: true }).waitFor();
    const totalModules = (await config()).tracks.reduce((count, track) => count + track.modules.length, 0);
    assert.equal(await page.locator(".curriculum-module").count(), totalModules, "Modules defaults to all tracks");
    await select(t(C.filterTrack), trackTitle("first-steps"));
    await page.waitForURL((url) => url.searchParams.get("track") === "first-steps");
    assert.equal(await page.locator(".curriculum-module").count(), (await config()).tracks.find((track) => track.id === "first-steps").modules.length);
    await select(t(C.filterTrack), trackTitle("explore"));
    await page.waitForURL((url) => url.searchParams.get("track") === "explore");
    const sectionName = `UI section ${label}`;
    const sectionAr = `قسم التحقق ${label}`;
    await button(t(C.addSection)).click();
    await select(t(C.track), trackTitle("first-steps"));
    await editTitle(sectionName, sectionAr);
    await saveDialog("tracks/first-steps");
    await page.waitForURL((url) => url.searchParams.get("track") === "first-steps");
    const section = () => page.locator(".curriculum-module").filter({ has: page.locator("h3").filter({ hasText: lang === "en" ? sectionName : sectionAr }) });
    await select(t(C.filterTrack), t(C.allTracks));
    await page.waitForURL((url) => url.searchParams.get("track") === "all");
    let data = await config();
    const originalModule = data.tracks.find((track) => track.id === "first-steps").modules[0];
    const originalRow = page.locator(".curriculum-module").filter({ has: page.getByRole("heading", { name: t(originalModule.title), exact: true }) });
    await originalRow.getByRole("button", { name: t(C.edit), exact: true }).click();
    assert.equal(await page.getByRole("dialog").getByRole("textbox").count(), 2, "Renaming only exposes bilingual names");
    assert.equal(await page.getByRole("dialog").getByRole("combobox").count(), 0);
    await editTitle(`${originalModule.title.en} renamed`, `${originalModule.title.ar} المعدلة`);
    await saveDialog("tracks/first-steps");
    const renamedModule = (await config()).tracks.find((track) => track.id === "first-steps").modules.find((m) => m.id === originalModule.id);
    assert.deepEqual({ ...renamedModule, title: originalModule.title }, originalModule, "Renaming preserves goal, courses and other module content");
    assert.equal(await page.locator(".curriculum-module-row select").count(), 0, "Position pickers belong to courses inside modules");
    const occupied = (await config()).tracks.flatMap((track) => track.modules).find((module) => module.lessons.length);
    const occupiedRow = page.locator(".curriculum-module").filter({ has: page.getByRole("heading", { name: t(occupied.title), exact: true }) });
    assert(await occupiedRow.getByRole("button", { name: t(C.delete), exact: true }).isDisabled(), "Modules with courses cannot be deleted");
    assert(await section().getByRole("button", { name: t(C.delete), exact: true }).isEnabled(), "Empty modules can be deleted");
    assert.equal(await button(t(C.addCourse)).count(), 0);
    const beforeOrder = await config();
    await waitSave(() => section().getByRole("button", { name: `${t(C.up)}: ${lang === "en" ? sectionName : sectionAr}`, exact: true }).click(), "tracks/first-steps");
    const afterOrder = await config();
    const beforeModules = beforeOrder.tracks.find((track) => track.id === "first-steps").modules;
    const expectedOrder = [...beforeModules];
    [expectedOrder[expectedOrder.length - 2], expectedOrder[expectedOrder.length - 1]] = [expectedOrder[expectedOrder.length - 1], expectedOrder[expectedOrder.length - 2]];
    assert.deepEqual(afterOrder.tracks.find((track) => track.id === "first-steps").modules, expectedOrder);
    assert.deepEqual(afterOrder.tracks.filter((track) => track.id !== "first-steps"), beforeOrder.tracks.filter((track) => track.id !== "first-steps"));
    // Exercise three or more real lessons, including full-list jumps, arrows and reload persistence.
    const lessonConfig = await config();
    const lessonTrack = lessonConfig.tracks.find((track) => track.modules.some((module) => module.lessons.length >= 3));
    assert(lessonTrack, "Fixture needs a module with at least three lessons");
    const lessonModule = lessonTrack.modules.find((module) => module.lessons.length >= 3);
    const lessonRow = () => page.locator(".curriculum-module").filter({ has: page.getByRole("heading", { name: t(lessonModule.title), exact: true }) });
    const initial = [...lessonModule.lessons];
    const nameFor = (id) => {
      const course = lessonConfig.courses.find((course) => course.id === id);
      return course ? t(course.title) : id;
    };
    const orderFor = (id) => lessonRow().getByRole("combobox", { name: `${t(C.order)}: ${nameFor(id)}`, exact: true });
    const last = initial.at(-1);
    const beforeCourses = await (await page.request.get(`${api}/api/review/courses`)).json();
    await waitSave(() => orderFor(last).selectOption({ value: "0" }), `tracks/${lessonTrack.id}`);
    const jumped = [last, ...initial.slice(0, -1)];
    const expectedTracks = lessonConfig.tracks.map((track) => track.id === lessonTrack.id ? { ...track, modules: track.modules.map((module) => module.id === lessonModule.id ? { ...module, lessons: jumped } : module) } : track);
    assert.deepEqual((await config()).tracks, expectedTracks, "Only the selected module's lesson order changes");
    assert.deepEqual(await orderFor(last).locator("option").allTextContents(), initial.map((_, i) => String(i + 1)), "Only positions 1 through N are available");
    await page.reload();
    await lessonRow().locator(".curriculum-course-row").first().waitFor();
    assert.deepEqual(await lessonRow().locator(".curriculum-course-row a").allTextContents(), jumped.map(nameFor));
    assert.deepEqual(await lessonRow().locator(".curriculum-course-row select").evaluateAll((nodes) => nodes.map((node) => node.value)), initial.map((_, i) => String(i)), "Positions stay consecutive after reloading");
    assert(await lessonRow().getByRole("button", { name: `${t(C.up)}: ${nameFor(last)}`, exact: true }).isDisabled());
    await waitSave(() => lessonRow().getByRole("button", { name: `${t(C.down)}: ${nameFor(last)}`, exact: true }).click(), `tracks/${lessonTrack.id}`);
    await waitSave(() => lessonRow().getByRole("button", { name: `${t(C.up)}: ${nameFor(last)}`, exact: true }).click(), `tracks/${lessonTrack.id}`);
    assert.deepEqual(await (await page.request.get(`${api}/api/review/courses`)).json(), beforeCourses, "Reordering keeps course content and statuses unchanged");
    const publicContent = await (await page.request.get(`${api}/api/content`)).json();
    assert.deepEqual(publicContent.tracks.find((track) => track.id === lessonTrack.id).modules.find((module) => module.id === lessonModule.id).lessons, jumped);
    await screenshot("lesson-order");
    profile = { ...profile, preferred_track: lessonTrack.id };
    await page.goto(`${base}/learn/`);
    await button(t(lessonModule.title)).click();
    const journey = page.locator("section").filter({ has: page.getByRole("heading", { name: t(S.dash.journey), exact: true }) });
    const visibleIds = jumped.filter((id) => publicContent.courses[id] || publicContent.coming_soon?.[id]);
    assert.deepEqual(await journey.locator("ol > li").evaluateAll((nodes) => nodes.map((node) => node.querySelector("span.block.text-sm")?.textContent)), visibleIds.map(nameFor), "The learner journey follows Studio ordering");
    await page.goto(`${base}/studio/curriculum/?tab=modules&track=all`);
    await orderFor(last).waitFor();
    await waitSave(() => orderFor(last).selectOption({ value: String(initial.length - 1) }), `tracks/${lessonTrack.id}`);
    assert.deepEqual((await config()).tracks, lessonConfig.tracks);
    await screenshot("modules");
    await section().getByRole("button", { name: t(C.delete), exact: true }).click();
    await page.getByRole("dialog").getByRole("button", { name: t(C.cancel), exact: true }).click();
    assert((await config()).tracks.find((track) => track.id === "first-steps").modules.some((module) => module.title.en === sectionName));
    await section().getByRole("button", { name: t(C.delete), exact: true }).click();
    await removeDialog("tracks/first-steps");
    assert(!(await config()).tracks.find((track) => track.id === "first-steps").modules.some((module) => module.title.en === sectionName));
    await goTab("subjects");
    // An external editor changes the row while this page holds the old timestamp.
    data = await config();
    const changed = data.subjects.map((s) => s.id === subject.id ? { ...s, title: { en: `${name} external`, ar: arName } } : s);
    assert.equal((await page.request.post(`${api}/api/curriculum/subjects`, { data: { subjects: changed, updated_at: data.updated_at.subjects } })).status(), 200);
    await page.locator("tbody tr").filter({ hasText: `${name} renamed` }).getByRole("button", { name: t(C.edit), exact: true }).click();
    await page.getByRole("dialog").getByRole("button", { name: t(C.save), exact: true }).click();
    await page.getByRole("dialog").getByRole("alert").getByText(t(C.stale), { exact: true }).waitFor();
    await page.getByRole("dialog").getByRole("button", { name: t(C.cancel), exact: true }).click();
    await page.reload();
    await page.getByText(`${name} external`, { exact: true }).waitFor();
    await page.locator("tbody tr").filter({ hasText: `${name} external` }).getByRole("button", { name: t(C.delete), exact: true }).click();
    await removeDialog("subjects");
    assert(!((await config()).subjects.some((s) => s.id === subject.id)));
    assert.deepEqual(errors, []);
    console.log(`${label}: curriculum CRUD, module ordering, course positions inside modules, arrows, reload persistence, learner journey order, preserved content, layout and stale recovery passed.`);
    await context.close();
  }
} finally { await browser.close(); }
